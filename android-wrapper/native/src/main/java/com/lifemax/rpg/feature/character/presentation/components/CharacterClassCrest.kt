@Composable
internal fun CharacterClassCrest(classId: String, modifier: Modifier = Modifier) {
    val crest = crests[classId] ?: return
    Canvas(modifier) {
        val unit = size.minDimension / 32f
        val alphabet = "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789"
        crest.rows.forEachIndexed { y, row ->
            row.forEachIndexed { x, c ->
                if (c != '.')
                    drawRect(
                        crest.palette[alphabet.indexOf(c)],
                        Offset(x * unit, y * unit),
                        Size(unit, unit),
                    )
            }
        }
    }
}
