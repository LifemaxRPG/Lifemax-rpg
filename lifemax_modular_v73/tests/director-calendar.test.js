'use strict';
const fs = require('fs'), path = require('path'), vm = require('vm'), assert = require('assert/strict');
const base = process.env.DIRECTOR_SOURCE || path.join(__dirname, '../src/features/life-director');
const engine = fs.readFileSync(path.join(base, 'engine.js'), 'utf8');
const logic = fs.readFileSync(path.join(base, 'logic.js'), 'utf8');
const sandbox = { module: { exports: {} } };
vm.runInNewContext(engine.slice(0, engine.indexOf('/* ── Life Director Store')), sandbox);
const U = sandbox.module.exports.util;
let now = Date.parse('2026-11-06T12:00:00Z') / 1000;
const zone = 'America/New_York';
const ST = { setupComplete: true, schedule: { saved: true }, ui: { focus: { id: 'keep-timer' } } };
const before = JSON.stringify(ST);
const ctx = { U, ST, ui: { dayIdx: 0, tab: 'today' }, nowEpoch: () => now, tz: () => zone,
  horizonDays: () => U.buildHorizon(now, 7, zone), changed() {}, root: null };
const start = logic.indexOf('  let nativeCalendarOffset = null;');
const end = logic.indexOf('  /* ── Today', start);
assert(start > 0 && end > start);
const api = vm.runInNewContext(logic.slice(start, end) + '\n({days:calendarDays,select:nativeDay,offset:()=>nativeCalendarOffset})', ctx);
assert.equal(api.select(400, false).ok, true);
assert.equal(api.offset(), 400);
api.select(400, false);
assert.equal(api.offset(), 400, 'replayed selection must not advance again');
assert.equal(api.days(400, zone).length, 7);
assert.equal(api.select(-40, false).ok, true);
assert.equal(api.offset(), -40);
assert.equal(api.select(NaN, false).ok, false);
assert.equal(api.offset(), -40);
api.select(0, true);
assert.equal(api.offset(), null, 'Week/Today navigation exits remote calendar browsing');
assert.equal(ctx.ui.dayIdx, 0);
now = Date.parse('2026-10-31T12:00:00Z') / 1000;
const fall = api.days(1, zone)[0];
assert.equal(fall.ymd.d, 1);
assert.equal(fall.endEpoch - fall.startEpoch, 25 * 3600, 'DST uses local calendar days');
now = Date.parse('2028-02-28T12:00:00Z') / 1000;
assert.equal(api.days(1, zone)[0].ymd.d, 29);
assert.equal(api.days(2, zone)[0].ymd.mo, 3);
assert.equal(JSON.stringify(ST), before, 'browsing must not write the schedule or timer');
console.log('PASS unbounded calendar browsing, replay, invalid input, DST, leap day, save isolation');
