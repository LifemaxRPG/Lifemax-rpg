'use strict';
const fs = require('fs'), vm = require('vm'), assert = require('assert/strict'), path = require('path');
const base = process.env.DIRECTOR_SOURCE || path.join(__dirname, '../src/features/life-director');
const engine = fs.readFileSync(path.join(base, 'engine.js'), 'utf8');
const logic = fs.readFileSync(path.join(base, 'logic.js'), 'utf8');
const sandbox = { module: { exports: {} } };
vm.runInNewContext(engine.slice(0, engine.indexOf('/* ── Life Director Store')), sandbox);
const U = sandbox.module.exports.util;
let now;
const schedule = { horizonStartEpoch: Date.parse('2026-11-04T12:00:00Z') / 1000, horizonEndEpoch: Date.parse('2026-11-11T12:00:00Z') / 1000, scheduledInstances: [{ instanceId: 'running' }] };
const ST = { schedule, ui: { focus: { id: 'running' } } };
const before = JSON.stringify(ST);
const start = logic.indexOf('  function horizonDays(');
const end = logic.indexOf('\n  }', start) + 4;
const get = vm.runInNewContext(logic.slice(start, end) + '\nhorizonDays', { U, ST, nowEpoch: () => now });
const zone = 'America/New_York';
now = Date.parse('2026-11-05T04:59:59Z') / 1000;
assert.equal(get(schedule, zone)[0].ymd.d, 4);
now++;
assert.equal(get(schedule, zone)[0].ymd.d, 5);
now = Date.parse('2026-11-05T10:25:00Z') / 1000;
const today = get(schedule, zone)[0];
assert.equal(today.ymd.d, 5);
assert(now >= today.startEpoch && now < today.endEpoch, 'hand is inside the selected day');
assert.equal(get({ ...schedule }, zone)[0].ymd.d, 4, 'lab schedules stay fixed');
now = Date.parse('2026-11-20T10:25:00Z') / 1000;
assert.equal(get(schedule, zone)[0].ymd.d, 20, 'expired plans still show the real date');
assert.equal(JSON.stringify(ST), before, 'timer and scheduled instances are preserved');
console.log('PASS midnight rollover, morning hand, lab isolation, expired horizon, timer preservation');
