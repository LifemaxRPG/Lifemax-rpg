#!/usr/bin/env python3
"""Packs the sound effects in art/sfx/src (Kenney Casino Audio, CC0) into src/runtime/segments/50-sfx-data.js.
Each file is re-encoded to mono Vorbis to keep the app small. Run from lifemax_modular_v73:  python3 tools/make_sfx.py
Only the groups listed in USE are included. To add sounds, drop .ogg files into art/sfx/src, add the group name here, and rerun."""
import base64, glob, os, subprocess, tempfile, json
USE = ('ui-', 'card-', 'cards-pack', 'dice-', 'die-', 'chips-handle', 'chips-stack', 'chip-lay')
data = {}; total = 0
for f in sorted(glob.glob('art/sfx/src/*.ogg')):
    name = os.path.splitext(os.path.basename(f))[0]
    if not name.startswith(USE): continue
    out = tempfile.mktemp(suffix='.ogg')
    subprocess.run(['ffmpeg', '-v', 'error', '-y', '-i', f, '-ac', '1', '-c:a', 'libvorbis', '-q:a', '2', out], check=True)
    b = open(out, 'rb').read(); os.remove(out); total += len(b)
    data[name] = base64.b64encode(b).decode()
js = '/* generated by tools/make_sfx.py from art/sfx/src (Kenney Casino Audio, CC0). Do not edit by hand. */\nvar SFX_DATA=' + json.dumps(data, separators=(',', ':')) + ';\n'
open('src/runtime/segments/50-sfx-data.js', 'w').write(js)
print(len(data), 'sounds', total // 1024, 'KB raw,', len(js) // 1024, 'KB in app')
