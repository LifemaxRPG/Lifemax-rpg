#!/usr/bin/env python3
"""Shrinks the table textures in art/table/src and writes src/runtime/segments/50-quests-table-data.js (the OBJ text plus three WebP textures).
Run from lifemax_modular_v73:  python3 tools/make_table_art.py"""
import base64, io, json
from PIL import Image
spec = {'base': ('base.png', 1024, 76), 'normal': ('normal.png', 1024, 82), 'orm': ('orm.png', 512, 80)}
tex = {}
for k, (f, size, q) in spec.items():
    im = Image.open('art/table/src/' + f).convert('RGB').resize((size, size), Image.LANCZOS)
    b = io.BytesIO(); im.save(b, 'WEBP', quality=q, method=6)
    tex[k] = base64.b64encode(b.getvalue()).decode(); print(k, size, len(b.getvalue()) // 1024, 'KB')
obj = open('art/table/src/table.obj').read()
lines = [l for l in obj.splitlines() if l.split()[:1] and l.split()[0] in ('v', 'vt', 'vn', 'f')]
js = '/* generated by tools/make_table_art.py from art/table/src. Do not edit by hand. */\n'
js += 'var TABLE_OBJ=' + json.dumps('\n'.join(lines)) + ';\n'
js += 'var TABLE_TEX=' + json.dumps(tex) + ';\n'
open('src/runtime/segments/50-quests-table-data.js', 'w').write(js)
print('wrote', len(js) // 1024, 'KB')
