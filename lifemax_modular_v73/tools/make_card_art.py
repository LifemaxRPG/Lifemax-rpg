#!/usr/bin/env python3
"""Shrinks the painted tarot cards in art/cards/src/*.png to WebP and writes src/runtime/segments/50-quests-art.js.
Run from lifemax_modular_v73:  python3 tools/make_card_art.py
Each source is named after what it is for: physique, endurance, intelligence, business, social, adventure, wellbeing, discipline, back."""
import base64, glob, io, os
from PIL import Image
W = 640
out = {}
for f in sorted(glob.glob('art/cards/src/*.png')):
    key = os.path.splitext(os.path.basename(f))[0]
    im = Image.open(f).convert('RGB')
    h = round(im.height * W / im.width)
    im = im.resize((W, h), Image.LANCZOS)
    b = io.BytesIO(); im.save(b, 'WEBP', quality=74, method=6)
    out[key] = (base64.b64encode(b.getvalue()).decode(), im.getpixel((5, h // 2)))
    print(key, im.size, len(b.getvalue()) // 1024, 'KB')
js = '/* generated by tools/make_card_art.py from art/cards/src. Do not edit by hand. */\nvar QART_B64={' + ','.join("'%s':'%s'" % (k, v[0]) for k, v in out.items()) + '};\n'
js += "var QART_EDGE={" + ','.join("'%s':'#e9cf9c'" % k for k, v in out.items()) + '};\n'
js += r'''var QART_URL={};
function qartUrl(k){
 if(!QART_B64[k])return null;
 if(!QART_URL[k]){
  try{const bin=atob(QART_B64[k]),u=new Uint8Array(bin.length);for(let i=0;i<bin.length;i++)u[i]=bin.charCodeAt(i);QART_URL[k]=URL.createObjectURL(new Blob([u],{type:'image/webp'}))}
  catch(e){QART_URL[k]=null}
 }
 return QART_URL[k];
}
'''
open('src/runtime/segments/50-quests-art.js', 'w').write(js)
print('wrote segment', len(js) // 1024, 'KB')
