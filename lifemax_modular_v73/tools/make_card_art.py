#!/usr/bin/env python3
"""Builds every card-art pack into src/runtime/segments/50-quests-art.js.
Run from lifemax_modular_v73:  python3 tools/make_card_art.py

A pack is a folder  art/cards/packs/<id>/  holding
  pack.json   {"name": "Halloween", "season": {"from": "10-01", "to": "11-02"} or null, "panel": {"default": [top%, bottomInset%], "<attribute>": [..]}}
  src/<attribute>.png  physique endurance intelligence business social adventure wellbeing discipline, and back.png
Missing files are fine: that card falls back to the Classic pack. 'season' is used by the Auto choice in Settings (month-day, may wrap the new year).
Panel numbers say where the parchment text area sits: its top edge as a percent of the card height, and how far its bottom edge is from the card bottom."""
import base64, glob, io, json, os
from PIL import Image
W = 640
root = 'art/cards/packs'
packs = {}
for d in sorted(glob.glob(root + '/*/')):
    pid = os.path.basename(os.path.normpath(d))
    meta = json.load(open(d + 'pack.json')) if os.path.exists(d + 'pack.json') else {}
    imgs = {}
    for f in sorted(glob.glob(d + 'src/*.png')):
        key = os.path.splitext(os.path.basename(f))[0]
        im = Image.open(f).convert('RGB'); h = round(im.height * W / im.width)
        im = im.resize((W, h), Image.LANCZOS)
        b = io.BytesIO(); im.save(b, 'WEBP', quality=74, method=6)
        imgs[key] = base64.b64encode(b.getvalue()).decode()
        print(pid, key, len(b.getvalue()) // 1024, 'KB')
    packs[pid] = {'name': meta.get('name', pid), 'season': meta.get('season'), 'panel': meta.get('panel', {'default': [69.3, 10.6]}), 'keys': sorted(imgs), 'img': imgs}
js = '/* generated by tools/make_card_art.py from art/cards/packs. Do not edit by hand. */\n'
js += 'var QART_PACKS=' + json.dumps({k: {kk: vv for kk, vv in v.items() if kk != 'img'} for k, v in packs.items()}, separators=(',', ':')) + ';\n'
js += 'var QART_B64=' + json.dumps({k: v['img'] for k, v in packs.items()}, separators=(',', ':')) + ';\n'
js += r'''var QART_URL={};
function qartPref(){try{return localStorage.getItem('lma_qpack')||'auto'}catch(e){return 'auto'}}
function qartSeasonal(){const d=new Date(),k=String(d.getMonth()+1).padStart(2,'0')+'-'+String(d.getDate()).padStart(2,'0');
 for(const id in QART_PACKS){const s=QART_PACKS[id].season;if(!s)continue;const inR=s.from<=s.to?(k>=s.from&&k<=s.to):(k>=s.from||k<=s.to);if(inR)return id}return 'classic'}
function qartPackId(){const p=qartPref();return p==='auto'?qartSeasonal():(QART_PACKS[p]?p:'classic')}
function qartSetPack(v){try{localStorage.setItem('lma_qpack',v)}catch(e){}toast('Card art: '+(v==='auto'?'automatic by season':(QART_PACKS[v]?QART_PACKS[v].name:v)));try{dhSig='';if(typeof dhRenderHand==='function')dhRenderHand()}catch(e){}}
/* which pack actually supplies a given card: the chosen one, else Classic */
function qartSource(k){const id=qartPackId();return QART_B64[id]&&QART_B64[id][k]?id:(QART_B64.classic&&QART_B64.classic[k]?'classic':null)}
function qartUrl(k){
 const src=qartSource(k);if(!src)return null;const key=src+'/'+k;
 if(!QART_URL[key]){
  try{const bin=atob(QART_B64[src][k]),u=new Uint8Array(bin.length);for(let i=0;i<bin.length;i++)u[i]=bin.charCodeAt(i);QART_URL[key]=URL.createObjectURL(new Blob([u],{type:'image/webp'}))}
  catch(e){QART_URL[key]=null}
 }
 return QART_URL[key];
}
function qartPanel(k){const src=qartSource(k),P=src&&QART_PACKS[src]?QART_PACKS[src].panel:null;return (P&&(P[k]||P['default']))||[69.3,10.6]}
setTimeout(function(){try{const s=document.getElementById('qpackSel');if(s){s.innerHTML='<option value="auto">Automatic (by season)</option>'+Object.keys(QART_PACKS).map(function(id){return '<option value="'+id+'">'+QART_PACKS[id].name+'</option>'}).join('');s.value=qartPref()}}catch(e){}},0);
'''
open('src/runtime/segments/50-quests-art.js', 'w').write(js)
print('wrote segment', len(js) // 1024, 'KB')
